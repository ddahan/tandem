// Extracts the file-type icons Tandem uses from @iconify-json/vscode-icons into
// app/utils/file-icons.generated.ts (a few KB, instead of the whole collection):
//   ./td pnpm --filter @tandem/web file-icons
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { getIconData, iconToHTML, iconToSVG, replaceIDs } from '@iconify/utils'
import { FILE_ICON_NAMES } from '../app/utils/file-icon-map.ts'

const require = createRequire(import.meta.url)
const collection = JSON.parse(
  readFileSync(require.resolve('@iconify-json/vscode-icons/icons.json'), 'utf8'),
) as Parameters<typeof getIconData>[0]

const svgs: Record<string, string> = {}
for (const name of FILE_ICON_NAMES) {
  const data = getIconData(collection, name)
  if (!data) throw new Error(`Unknown vscode-icons icon: ${name}`)
  const { attributes, body } = iconToSVG(data, { height: 'auto' })
  // Unique ids per icon: several icons with gradients can be on the same page.
  svgs[name] = iconToHTML(replaceIDs(body, name), attributes)
}

const output = new URL('../app/utils/file-icons.generated.ts', import.meta.url)
writeFileSync(
  output,
  `// Generated by scripts/file-icons.ts from @iconify-json/vscode-icons (MIT): don't edit.
// Regenerate after changing file-icon-map.ts: ./td pnpm --filter @tandem/web file-icons

export const FILE_ICON_SVGS: Record<string, string> = ${JSON.stringify(svgs, null, 2)}
`,
)
console.log(`${Object.keys(svgs).length} icons → app/utils/file-icons.generated.ts`)
